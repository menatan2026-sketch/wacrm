import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { elevation, fontStacks, motion, radius, themes } from "../src/index";

export function buildCss(): string {
  const vars = (t: Record<string, string>) => Object.entries(t).map(([k, v]) => `  --mfg-${k}: ${v};`).join("\n");
  const shared = [
    ...Object.entries(radius).map(([k, v]) => `  --mfg-radius-${k}: ${v};`),
    ...Object.entries(elevation).map(([k, v]) => `  --mfg-elevation-${k}: ${v};`),
    ...Object.entries(motion.duration).map(([k, v]) => `  --mfg-duration-${k}: ${v}ms;`),
    ...Object.entries(motion.easing).map(([k, v]) => `  --mfg-ease-${k}: ${v};`),
    `  --mfg-font-sans: ${fontStacks.sans};`,
    `  --mfg-font-mono: ${fontStacks.mono};`,
    "  --mfg-motion-inline: 1;",
  ].join("\n");
  return `/* Generated by packages/tokens/scripts/build-css.ts — do not edit by hand. */
:root {
${vars(themes.light)}
${shared}
  color-scheme: light;
}
:root[data-theme="dark"] {
${vars(themes.dark)}
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(themes.dark).replace(/^ {2}/gm, "    ")}
    color-scheme: dark;
  }
}
[dir="rtl"] {
  --mfg-motion-inline: -1;
}
/* Reduced motion: every duration collapses; information stays (MOTION_SYSTEM.md §6). */
@media (prefers-reduced-motion: reduce) {
  :root:not([data-motion="full"]) {
${Object.keys(motion.duration).map((k) => `    --mfg-duration-${k}: 0ms;`).join("\n")}
  }
}
:root[data-motion="reduced"] {
${Object.keys(motion.duration).map((k) => `  --mfg-duration-${k}: 0ms;`).join("\n")}
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(fileURLToPath(new URL("../src/tokens.css", import.meta.url)), buildCss());
  console.log("tokens.css written");
}
