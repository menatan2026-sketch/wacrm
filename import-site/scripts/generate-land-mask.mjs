/**
 * Generates the land mask used by the sourcing globe.
 *
 * Points are distributed on a Fibonacci sphere; each point that falls on
 * land (Natural Earth 110m, via world-atlas) sets one bit. The result is a
 * base64 bitset — ~10 KB for 60k points — so the globe needs no texture
 * and no runtime geo library.
 *
 *   node scripts/generate-land-mask.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const COUNT = 60000;
const topo = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)),
);
const land = feature(topo, topo.objects.land);

const bits = new Uint8Array(Math.ceil(COUNT / 8));
const golden = Math.PI * (3 - Math.sqrt(5));
let onLand = 0;

for (let i = 0; i < COUNT; i++) {
  const y = 1 - (i / (COUNT - 1)) * 2;
  const theta = golden * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lng = ((((theta * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (lat < -60) continue; // skip Antarctica — it reads as noise at the bottom of the globe
  if (geoContains(land, [lng, lat])) {
    bits[i >> 3] |= 1 << (i & 7);
    onLand++;
  }
}

const out = `// Generated by scripts/generate-land-mask.mjs — do not edit by hand.
// Fibonacci-sphere land mask (${COUNT} points, ${onLand} on land).
export const LAND_MASK_COUNT = ${COUNT};
export const LAND_MASK_BASE64 =
  "${Buffer.from(bits).toString("base64")}";
`;
writeFileSync(new URL("../src/data/generated/land-mask.ts", import.meta.url), out);
console.log(`land points: ${onLand}/${COUNT}`);
